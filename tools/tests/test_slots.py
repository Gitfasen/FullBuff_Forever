try:
    from lupa.lua51 import LuaRuntime
except ImportError:  # pragma: no cover
    from lupa import LuaRuntime

ROOT = Path(__file__).resolve().parents[2]
BUFFS_LUA = ROOT / "addon" / "FullBuff" / "Data" / "Buffs.lua"


def buff(bid, name, cat, excl, burst=False, fx=None):
    return Buff(id=bid, name=name, cat=cat, fx=fx or {"INT": 1}, dur=3600, lvl=1, excl=excl,
                items=[], burst=burst, new=False)


INT_SLOT = {"slots": [{"id": "INT", "name": {"en": "Intellect", "uk": "Інтелект"},
                       "groups": ["CLASS:Arcane Intellect", "SCROLL:INT"]}]}


def test_slot_merges_across_categories():
    buffs = {1: buff(1, "Arcane Intellect", "CLASS", "CLASS:Arcane Intellect"),
             2: buff(2, "Intellect", "SCROLL", "SCROLL:INT"),
             3: buff(3, "Boosted Intellect", "CAMPING", "CLASS:Arcane Intellect")}
    slots, warnings = apply_slots(buffs, INT_SLOT)
    assert warnings == []
    assert {b.excl for b in buffs.values()} == {"INT"}
    assert slots["INT"]["name"] == {"en": "Intellect", "uk": "Інтелект"}
    assert list(slots) == ["INT"]


def test_unknown_group_warns():
    buffs = {1: buff(1, "Arcane Intellect", "CLASS", "CLASS:Arcane Intellect")}
    cur = {"slots": [{"id": "INT", "name": {"en": "Intellect", "uk": "Інтелект"},
                      "groups": ["CLASS:Arcane Intellect", "SCROLL:INT"]}]}
    _, warnings = apply_slots(buffs, cur)
    assert warnings == ["slot INT: group SCROLL:INT matches no buff"]


def test_auto_names_en_uk():
    buffs = {1: buff(1, "Mongoose", "ELIXIR", "ELIXIR:AGI"),
             2: buff(2, "Agility", "SCROLL", "SCROLL:AGI"),
             3: buff(3, "Flask of Titans", "FLASK", "FLASK"),
             4: buff(4, "Sharpening", "WEAPON", "WEAPON"),
             5: buff(5, "Tender Wolf Steak", "FOOD", "FOOD:Well Fed"),
             9: buff(9, "Rat Familiar", "SCROLL", "SCROLL:Rat Familiar"),
             8: buff(8, "Cat Familiar", "SCROLL", "SCROLL:Rat Familiar")}
    slots, _ = apply_slots(buffs, {})
    assert slots["ELIXIR:AGI"]["name"] == {"en": "Elixir — Agility", "uk": "Еліксир — Спритність"}
    assert slots["SCROLL:AGI"]["name"] == {"en": "Scroll — Agility", "uk": "Сувій — Спритність"}
    assert slots["FLASK"]["name"] == {"en": "Flask", "uk": "Фласка"}
    assert slots["WEAPON"]["name"] == {"en": "Weapon", "uk": "Зброя"}
    assert slots["FOOD:Well Fed"]["name"] == {"en": "Food", "uk": "Їжа"}
    assert slots["SCROLL:Rat Familiar"]["name"] == {"en": "Cat Familiar", "uk": "Cat Familiar"}


def test_order_follows_category_then_name():
    buffs = {1: buff(1, "Tender", "FOOD", "FOOD:Well Fed"), 2: buff(2, "Fl", "FLASK", "FLASK"),
             3: buff(3, "Zed", "CLASS", "CLASS:Zed"), 4: buff(4, "Abe", "CLASS", "CLASS:Abe")}
    slots, _ = apply_slots(buffs, {})
    ranked = sorted(slots, key=lambda k: slots[k]["order"])
    assert ranked == ["CLASS:Abe", "CLASS:Zed", "FLASK", "FOOD:Well Fed"]


def test_burst_not_in_slots():
    buffs = {1: buff(1, "Potion", "POTION", "POTION:Potion", burst=True),
             2: buff(2, "Mongoose", "ELIXIR", "ELIXIR:AGI")}
    slots, _ = apply_slots(buffs, {})
    assert list(slots) == ["ELIXIR:AGI"]


def test_emit_slots_loads_in_lua(tmp_path):
    slots = {"INT": {"name": {"en": "Intellect", "uk": "Інтелект"}, "order": 1},
             "ELIXIR:AGI": {"name": {"en": "Elixir — Agility", "uk": "Еліксир — Спритність"}, "order": 2}}
    emit_slots(slots, tmp_path / "Slots.lua")
    text = (tmp_path / "Slots.lua").read_text(encoding="utf-8")
    assert text.startswith("-- GENERATED by tools/build.py. Do not edit.\nlocal _, ns = ...\n")
    lua = LuaRuntime(unpack_returned_tuples=True)
    ns = lua.eval("{}")
    lua.eval("function(src, ns) return loadstring(src, '=emitted')(nil, ns) end")(text, ns)
    assert ns.Slots["INT"].name.uk == "Інтелект"
    assert ns.Slots["INT"].order == 1
    assert ns.Slots["ELIXIR:AGI"].name.en == "Elixir — Agility"


def real_excl():
    out = {}
    for m in re.finditer(r'\[(\d+)\] = \{name="([^"]*)", cat="([^"]*)".*?excl="([^"]*)"',
                         BUFFS_LUA.read_text(encoding="utf-8")):
        out[(m.group(2), m.group(3))] = m.group(4)
    return out


def test_real_data_intellect_slot():
    ex = real_excl()
    assert (ex[("Arcane Intellect", "CLASS")] == ex[("Intellect", "SCROLL")]
            == ex[("Boosted Intellect", "CAMPING")] == "INT")
    assert ex[("Agility", "SCROLL")] != next(v for (n, c), v in ex.items() if c == "ELIXIR" and v == "ELIXIR:AGI")
