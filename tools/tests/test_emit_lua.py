import lupa

from tools.emit_lua import emit_buffs, emit_sources, emit_weights, write_report
from tools.model import Buff, Rank, Source

try:
    from lupa.lua51 import LuaRuntime
except ImportError:  # pragma: no cover
    from lupa import LuaRuntime


def mongoose():
    return Buff(id=17538, name="Elixir of the Mongoose", cat="ELIXIR", fx={"AGI": 25, "CRIT": 2},
                dur=3600, lvl=46, excl="ELIXIR:Elixir of the Mongoose", items=[13452],
                burst=False, new=False,
                sources=[Source("vendor", "Kelsey", 37, 0.272, 0.77), Source("quest", "A Quest"),
                         Source("craft", "Alchemy", note="215")])


def run(path):
    lua = LuaRuntime(unpack_returned_tuples=True)
    ns = lua.eval("{}")
    lua.eval("function(src, ns) return loadstring(src, '=emitted')(nil, ns) end")(
        path.read_text(encoding="utf-8"), ns)
    return ns


def test_emitted_buffs_load_in_lua(tmp_path):
    cls = Buff(id=1, name="Mark of the Wild", cat="CLASS", fx={"ARMOR": 285}, dur=1800, lvl=50,
               excl="CLASS:Mark", items=[], burst=False, new=True, cls="DRUID",
               ranks=[Rank(1126, 10, {"ARMOR": 25}), Rank(9885, 60, {"ARMOR": 285})], enchant=None)
    emit_buffs({17538: mongoose(), 1: cls}, tmp_path / "Buffs.lua")
    text = (tmp_path / "Buffs.lua").read_text(encoding="utf-8")
    assert text.startswith("-- GENERATED by tools/build.py. Do not edit.\nlocal _, ns = ...\n")
    ns = run(tmp_path / "Buffs.lua")
    b = ns.Buffs[17538]
    assert b.fx.AGI == 25
    assert (b.name, b.cat, b.dur, b.lvl, b["items"][1], b.burst, b.new) == (
        "Elixir of the Mongoose", "ELIXIR", 3600, 46, 13452, False, False)
    assert b.cls is None and b.ranks is None and b.enchant is None
    c = ns.Buffs[1]
    assert c.cls == "DRUID" and c.new is True
    assert c.ranks[2].spell == 9885 and c.ranks[2].fx.ARMOR == 285


def test_emitted_sources_and_weights_load(tmp_path):
    emit_sources({17538: mongoose(), 2: Buff(2, "x", "FOOD", {}, 1, 1, "", [], False, False)},
                 tmp_path / "Sources.lua")
    ns = run(tmp_path / "Sources.lua")
    s = ns.Sources[17538]
    assert (s[1].kind, s[1].mapID, s[1].x, s[1].y) == ("vendor", 37, 0.272, 0.77)
    assert s[2].mapID is None and s[2].x is None
    assert s[3].note == "215"
    assert ns.Sources[2] is None

    emit_weights({"WARRIOR": [{"AP": 1, "CRIT": 0.5}, {"STR": 2}, {"STA": 1}]}, tmp_path / "Weights.lua")
    ns = run(tmp_path / "Weights.lua")
    assert ns.Weights.WARRIOR[1].CRIT == 0.5 and ns.Weights.WARRIOR[2].STR == 2


def test_emit_escapes_quotes(tmp_path):
    name = 'Say "hi" \\ back\nslash über 中'
    b = mongoose()
    b.name = name
    b.sources = [Source("npc", name, note="it's")]
    emit_buffs({1: b}, tmp_path / "Buffs.lua")
    emit_sources({1: b}, tmp_path / "Sources.lua")
    assert run(tmp_path / "Buffs.lua").Buffs[1].name == name
    assert run(tmp_path / "Sources.lua").Sources[1][1].name == name
    assert "über" in (tmp_path / "Buffs.lua").read_text(encoding="utf-8")


def test_emit_rounds_coordinates(tmp_path):
    b = mongoose()
    b.sources = [Source("vendor", "n", 1, 0.123456789, 0.5)]
    emit_sources({1: b}, tmp_path / "Sources.lua")
    text = (tmp_path / "Sources.lua").read_text(encoding="utf-8")
    assert "x=0.1235" in text and "y=0.5}" in text


def test_emit_is_deterministic(tmp_path):
    a = {2: mongoose(), 1: mongoose()}
    b = {1: mongoose(), 2: mongoose()}
    emit_buffs(a, tmp_path / "a.lua")
    emit_buffs(b, tmp_path / "b.lua")
    assert (tmp_path / "a.lua").read_bytes() == (tmp_path / "b.lua").read_bytes()
    assert (tmp_path / "a.lua").read_text().index("[1]") < (tmp_path / "a.lua").read_text().index("[2]")


def test_report_sections(tmp_path):
    odd = Buff(9, "Odd|Thing", None, {"STR": 5}, 600, 0, "", [], False, False)
    write_report({17538: mongoose()}, [odd], ["warn one"], ["Camp X"], [4392], tmp_path / "r.md",
                 [("Camp Y", "Blessing")], 3)
    text = (tmp_path / "r.md").read_text(encoding="utf-8")
    for needle in ["ELIXIR: 1", "Odd\\|Thing", "warn one", "Camp X", "4392",
                   "Camp Y (exclusive with Blessing)", "craft source: 3"]:
        assert needle in text
