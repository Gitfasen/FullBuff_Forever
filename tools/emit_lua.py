"""Emit the generated Lua data files and the build report."""
import re
from collections import Counter
from pathlib import Path

from tools.model import Buff, Rank, Source

HEADER = "-- GENERATED by tools/build.py. Do not edit.\nlocal _, ns = ...\n"
IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
ESCAPES = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\0": "\\0"}


def lua_str(s: str) -> str:
    """Quoted Lua string literal; non-ASCII text is kept as UTF-8."""
    out = []
    for ch in s:
        if ch in ESCAPES:
            out.append(ESCAPES[ch])
        elif ord(ch) < 32 or ord(ch) == 127:
            out.append(f"\\{ord(ch):03d}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def lua_num(v: float, digits: int = 4) -> str:
    if isinstance(v, bool):
        raise TypeError("bool is not a number")
    if isinstance(v, int):
        return str(v)
    r = round(v, digits)
    if r == int(r):
        return str(int(r))
    return repr(r)


def _key(k: str) -> str:
    return k if IDENT_RE.match(k) else f"[{lua_str(k)}]"


def _fx(fx: dict[str, float]) -> str:
    return "{" + ", ".join(f"{_key(k)}={lua_num(fx[k])}" for k in sorted(fx)) + "}"


def _rank(r: Rank) -> str:
    return f"{{spell={r.spell}, lvl={r.lvl}, fx={_fx(r.fx)}}}"


def _buff(b: Buff) -> str:
    parts = [f"name={lua_str(b.name)}"]
    if b.cat is not None:
        parts.append(f"cat={lua_str(b.cat)}")
    parts.append(f"fx={_fx(b.fx)}")
    parts.append(f"dur={b.dur}")
    parts.append(f"lvl={b.lvl}")
    parts.append(f"excl={lua_str(b.excl)}")
    parts.append("items={" + ", ".join(str(i) for i in b.items) + "}")
    parts.append(f"burst={'true' if b.burst else 'false'}")
    parts.append(f"new={'true' if b.new else 'false'}")
    if b.cls is not None:
        parts.append(f"cls={lua_str(b.cls)}")
    if b.ranks is not None:
        parts.append("ranks={" + ", ".join(_rank(r) for r in b.ranks) + "}")
    if b.enchant is not None:
        parts.append(f"enchant={b.enchant}")
    if b.self_only:
        parts.append("selfOnly=true")
    if b.aura is not None and b.aura != b.id:
        parts.append(f"aura={b.aura}")
    return "{" + ", ".join(parts) + "}"


def _source(s: Source) -> str:
    parts = [f"kind={lua_str(s.kind)}", f"name={lua_str(s.name)}"]
    if s.mapID is not None:
        parts.append(f"mapID={s.mapID}")
    if s.x is not None:
        parts.append(f"x={lua_num(s.x)}")
    if s.y is not None:
        parts.append(f"y={lua_num(s.y)}")
    if s.note is not None:
        parts.append(f"note={lua_str(s.note)}")
    return "{" + ", ".join(parts) + "}"


def _write(path: Path, body: str) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + body, encoding="utf-8", newline="\n")


def emit_buffs(buffs: dict[int, Buff], path: Path) -> None:
    lines = ["ns.Buffs = {"]
    for bid in sorted(buffs):
        lines.append(f"  [{bid}] = {_buff(buffs[bid])},")
    lines.append("}")
    _write(path, "\n".join(lines) + "\n")


def emit_sources(buffs: dict[int, Buff], path: Path) -> None:
    lines = ["ns.Sources = {"]
    for bid in sorted(buffs):
        if buffs[bid].sources:
            lines.append(f"  [{bid}] = {{")
            lines.extend(f"    {_source(s)}," for s in buffs[bid].sources)
            lines.append("  },")
    lines.append("}")
    _write(path, "\n".join(lines) + "\n")


def emit_weights(weights: dict[str, list[dict[str, float]]], path: Path) -> None:
    lines = ["ns.Weights = {"]
    for cls in sorted(weights):
        specs = ", ".join(_fx(s) for s in weights[cls])
        lines.append(f"  {_key(cls)} = {{ {specs} }},")
    lines.append("}")
    _write(path, "\n".join(lines) + "\n")


def _cell(s: str) -> str:
    return s.replace("|", "\\|")


def write_report(buffs: dict[int, Buff], unclassified: list[Buff], warnings: list[str],
                 unmatched_camps: list[str], crosscheck: list[int], path: Path,
                 unresolved_exclusives: list[tuple[str, str]] = (),
                 craft_count: int | None = None, unobtainable: list[Buff] = (),
                 routeless: list[Buff] = ()) -> None:
    out = ["# FullBuff build report", "", "## Counts per category", ""]
    counts = Counter(b.cat for b in buffs.values())
    out += [f"- {cat}: {n}" for cat, n in sorted(counts.items(), key=lambda kv: str(kv[0]))]
    out.append(f"- total: {len(buffs)}")
    if craft_count is not None:
        out.append(f"- buffs with a craft source: {craft_count}")

    def section(title: str, lines: list[str]) -> None:
        out.extend(["", f"## {title} ({len(lines)})", ""])
        out.extend(lines or ["(none)"])

    section("New in Forever", [f"- {b.id} {b.name} [{b.cat}]" for _, b in sorted(buffs.items()) if b.new])
    section("Buffs without sources",
            [f"- {b.id} {b.name} [{b.cat}]" for _, b in sorted(buffs.items()) if not b.sources])
    section("Unclassified candidates",
            [f"- {b.id} | {_cell(b.name)} | dur {b.dur} | {_fx(b.fx)}"
             for b in sorted(unclassified, key=lambda b: b.id)])
    section("Warnings", [f"- {w}" for w in warnings])
    section("Unmatched camp buffs", [f"- {n}" for n in unmatched_camps])
    section("Unresolved camp exclusives", [f"- {n} (exclusive with {e})" for n, e in unresolved_exclusives])
    section("Cross-check misses (consumable item ids not in any buff)", [f"- {i}" for i in crosscheck])
    section("Excluded as unobtainable",
            [f"- {b.id} {b.name} [{b.cat}] items {', '.join(str(i) for i in b.items)}"
             for b in sorted(unobtainable, key=lambda b: b.id)])
    section("Item buffs without a Questie route (lvl stays at the item's RequiredLevel)",
            [f"- {b.id} {b.name} [{b.cat}] lvl {b.lvl} items {', '.join(str(i) for i in b.items)}"
             for b in sorted(routeless, key=lambda b: (b.cat != "QUEST", b.id))])
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
